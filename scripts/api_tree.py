#!/usr/bin/env python3
"""Generate the Ferro API map (docs/api/TREE.md), like the Revit API
namespace tree: crate → module → public items, each with the first line of
its doc comment.

    python3 scripts/api_tree.py           # rewrite docs/api/TREE.md
    python3 scripts/api_tree.py --check   # fail if the file is out of date

Only reads source files; no build needed. Items are listed in source order.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "api", "TREE.md")
CRATES = os.path.join(ROOT, "crates")

ITEM = re.compile(
    r"^pub(?:\(crate\))?\s+(?:async\s+)?(struct|enum|trait|fn|const|type|mod)\s+([A-Za-z_][A-Za-z0-9_]*)"
)
KIND = {"struct": "struct", "enum": "enum", "trait": "trait", "fn": "fn",
        "const": "const", "type": "type", "mod": "mod"}


def first_doc(lines, i):
    """First line of the `///` block right above line i (skipping attributes)."""
    j = i - 1
    while j >= 0 and lines[j].strip().startswith("#["):
        j -= 1
    block = []
    while j >= 0 and lines[j].strip().startswith("///"):
        block.append(lines[j].strip()[3:].strip())
        j -= 1
    block.reverse()
    for b in block:
        if b:
            return b
    return ""


def module_doc(lines):
    out = []
    for l in lines:
        s = l.strip()
        if s.startswith("//!"):
            t = s[3:].strip()
            if t:
                out.append(t)
            elif out:
                break
        elif s:
            break
    return " ".join(out)


def scan_file(path):
    """Public top-level items (indentation 0) and impl methods (indentation 4)."""
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    items = []
    in_test = False
    current_impl = None
    for i, raw in enumerate(lines):
        if raw.startswith("#[cfg(test)]"):
            in_test = True
        if in_test:
            continue
        m_impl = re.match(r"^impl(?:<[^>]*>)?\s+(?:([A-Za-z_][\w:<>, ]*)\s+for\s+)?([A-Za-z_]\w*)", raw)
        if m_impl:
            current_impl = None if m_impl.group(1) else m_impl.group(2)
            continue
        if raw.startswith("}"):
            current_impl = None
        if raw.startswith("pub"):
            m = ITEM.match(raw)
            if m and m.group(1) != "mod":
                items.append((m.group(1), m.group(2), first_doc(lines, i), None))
        elif current_impl and raw.startswith("    pub fn "):
            m = re.match(r"^    pub fn ([A-Za-z_]\w*)", raw)
            if m:
                items.append(("fn", m.group(1), first_doc(lines, i), current_impl))
    return module_doc(lines), items


def module_files(src):
    """(module path, file) for every .rs file under src, lib.rs first."""
    out = []
    for dirpath, _, files in os.walk(src):
        for name in files:
            if not name.endswith(".rs"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), src)
            parts = rel[:-3].split(os.sep)
            if parts[-1] in ("mod", "lib", "main"):
                parts = parts[:-1]
            if parts and parts[-1].endswith("_tests") or "tests" in parts:
                continue
            out.append(("::".join(parts), os.path.join(dirpath, name)))
    # Module path, then file: lib.rs and main.rs share the crate root, and
    # os.walk order differs between filesystems (CI vs local).
    out.sort(key=lambda x: (x[0], x[1].replace(os.sep, "/")))
    return out


def render():
    lines = [
        "# Ferro API map",
        "",
        "Generated by `scripts/api_tree.py` from the sources — do not edit by",
        "hand; run the script and commit. Like the Revit API namespace tree:",
        "crate → module → public items. Layers inside `ferro-core` depend",
        "downward only: `math → geom → topo → algo → model → ops` (D-19).",
        "",
        "Methods are listed under their type as `Type::method`.",
        "",
    ]
    for crate in sorted(os.listdir(CRATES)):
        src = os.path.join(CRATES, crate, "src")
        if not os.path.isdir(src):
            continue
        lines.append(f"## `{crate}`")
        lines.append("")
        for mod_path, path in module_files(src):
            doc, items = scan_file(path)
            if not items and not doc:
                continue
            name = f"{crate.replace('-', '_')}" + (f"::{mod_path}" if mod_path else "")
            lines.append(f"### `{name}`")
            if doc:
                lines.append("")
                lines.append(doc)
            lines.append("")
            for kind, ident, d, owner in items:
                label = f"{owner}::{ident}" if owner else ident
                lines.append(f"- {KIND[kind]} `{label}`" + (f" — {d}" if d else ""))
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print("docs/api/TREE.md is out of date: run python3 scripts/api_tree.py")
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
