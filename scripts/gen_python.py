#!/usr/bin/env python3
"""Generate the Python SDK's tool functions (ADR 0005 part 1, M5-14.2).

Reads the tool list that `ferro-mcp --tools-json` prints (the same JSON as
MCP `tools/list`) from the checked-in snapshot `python/ferro/tools.json` and
writes `python/ferro/_tools.py`: one keyword-only, typed function per tool,
named exactly as the tool, whose docstring is the tool description plus the
parameter descriptions with units.

    python3 scripts/gen_python.py            regenerate _tools.py from tools.json
    python3 scripts/gen_python.py --refresh  first rewrite tools.json from
                                             `cargo run -q -p ferro-mcp -- --tools-json`
    python3 scripts/gen_python.py --check    exit 1 if _tools.py is stale
                                             (scripts/lint.py runs this)

The output is deterministic: same tools.json, same bytes.
"""

import json
import keyword
import os
import subprocess
import sys
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(ROOT, "python", "ferro")
SNAPSHOT = os.path.join(PKG, "tools.json")
OUTPUT = os.path.join(PKG, "_tools.py")

LENGTH_NOTE = "Length: number = millimetres, or a string with units (\"3m\", \"300cm\")."
POINT_NOTE = "Point [x, y] or [x, y, z] in millimetres (or strings with units); Z is up."

HEADER = '''\
"""Generated by scripts/gen_python.py from tools.json -- DO NOT EDIT.

One function per Ferro tool (the same API as MCP, ADR 0005), named exactly as
the tool. Lengths are millimetres when given as numbers, or strings with
units ("3m"); points are [x, y, z] in millimetres; angles are degrees.
Arguments left as None are not sent, so the tool's default applies.

Each call goes to the document bound by ``ferro.connect()`` (or the
``Document`` whose helper is running) and returns the tool's JSON body.
Failures raise ``ferro.FerroError``.
"""

from typing import Any, Dict, Literal, Optional, Sequence, Tuple, TypedDict, Union

from ._runtime import call as _call

#: A length: number = millimetres, or a string with units ("3m", "300cm", "10'").
Length = Union[float, int, str]


class PointDict(TypedDict, total=False):
    """A point as a mapping; missing coordinates are 0. Millimetres."""

    x: Length
    y: Length
    z: Length


#: A point [x, y] or [x, y, z] in millimetres (or strings with units). Z is up.
Point = Union[Tuple[Length, Length], Tuple[Length, Length, Length], Sequence[Length], PointDict]

#: Document-local element id (as returned by list_elements / create_* tools).
ElementId = int
'''


def is_length(s):
    t = s.get("type")
    return isinstance(t, list) and sorted(t) == ["number", "string"] and "items" not in s


def is_point(s):
    return s.get("type") == "array" and is_length(s.get("items", {})) and s.get("maxItems") == 3


def py_type(s):
    """Python annotation for a JSON schema."""
    if "enum" in s:
        return "Literal[" + ", ".join(json.dumps(v) for v in s["enum"]) + "]"
    if is_point(s):
        return "Point"
    if is_length(s):
        return "Length"
    t = s.get("type")
    if isinstance(t, list):
        non_null = [x for x in t if x != "null"]
        inner = py_type(dict(s, type=non_null[0])) if len(non_null) == 1 else "Any"
        return f"Optional[{inner}]" if "null" in t else inner
    if t == "string":
        return "str"
    if t == "integer":
        return "ElementId" if s.get("description", "").lower().rstrip(")").endswith((" id", "id")) else "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "object":
        return "Dict[str, Any]"
    if t == "array":
        if s.get("description", "").startswith(("Element ids", "Form ids")):
            return "Sequence[ElementId]"
        return f"Sequence[{py_type(s.get('items', {}))}]"
    return "Any"


def describe(s):
    """One-line description of a parameter, with units."""
    parts = []
    desc = s.get("description", "")
    if is_point(s):
        parts.append(desc.split(" [x, y, z]")[0] + "." if desc else "")
        parts.append(POINT_NOTE)
    elif is_length(s):
        parts.append(LENGTH_NOTE)
    elif s.get("type") == "array" and s.get("items"):
        item = s["items"]
        if desc:
            parts.append(desc + ".")
        if is_point(item):
            parts.append("List of points [x, y, z] in millimetres.")
            if item.get("description"):
                parts.append("Each: " + item["description"].split(" [x, y, z]")[0] + ".")
        elif item.get("type") == "array" and is_point(item.get("items", {})):
            parts.append("List of point lists [x, y, z] in millimetres.")
        elif item.get("type") == "object" and item.get("properties"):
            fields = []
            req = set(item.get("required", []))
            for k, v in item["properties"].items():
                note = py_type(v)
                if is_length(v):
                    note = "length mm"
                fields.append(f"{k}{'' if k in req else '?'}: {note}")
            parts.append("Each item: {" + ", ".join(fields) + "}.")
    elif desc:
        parts.append(desc if desc.endswith(".") else desc + ".")
    for k in ("minimum", "maximum", "minItems", "maxItems"):
        if k in s and not (is_point(s) and k in ("minItems", "maxItems")):
            parts.append(f"{k}={s[k]}.")
    if "enum" in s:
        parts.append("One of: " + ", ".join(str(v) for v in s["enum"]) + ".")
    fallback = {"string": "Text.", "boolean": "True or False.", "integer": "Integer.",
                "number": "Number.", "object": "JSON object."}
    t = s.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), "")
        if "null" in s["type"]:
            fallback = {k: v[:-1] + " (None clears)." for k, v in fallback.items()}
    return " ".join(p for p in parts if p) or fallback.get(t, "Value.")


def py_name(name):
    return name + "_" if keyword.iskeyword(name) or name in ("link",) else name


def gen_function(tool):
    name = tool["name"]
    if not name.isidentifier() or keyword.iskeyword(name):
        raise SystemExit(f"tool name {name!r} is not a Python identifier")
    schema = tool.get("inputSchema", {})
    props = schema.get("properties", {})
    required = list(schema.get("required", []))
    # Required first (in schema order), then optional (sorted, deterministic).
    order = [k for k in required if k in props] + sorted(k for k in props if k not in required)
    params, doc_args, req_items, opt_items = [], [], [], []
    for k in order:
        s = props[k]
        pn = py_name(k)
        ann = py_type(s)
        if k in required:
            params.append(f"{pn}: {ann}")
            req_items.append(f"{json.dumps(k)}: {pn}")
        else:
            opt = ann if ann.startswith("Optional[") else f"Optional[{ann}]"
            params.append(f"{pn}: {opt} = None")
            opt_items.append((k, pn))
        label = "" if k in required else " Optional."
        doc_args.append((pn, describe(s) + label))

    sig = f"def {name}(*, {', '.join(params)}) -> Dict[str, Any]:" if params else f"def {name}() -> Dict[str, Any]:"
    lines = []
    if len(sig) > 99 and params:
        lines.append(f"def {name}(")
        lines.append("    *,")
        for p in params:
            lines.append(f"    {p},")
        lines.append(") -> Dict[str, Any]:")
    else:
        lines.append(sig)

    wrapper = textwrap.TextWrapper(width=88, initial_indent='    """', subsequent_indent="    ",
                                   break_on_hyphens=False, break_long_words=False)
    desc = " ".join(tool.get("description", name).split()).replace('"""', "'''")
    doc = wrapper.wrap(desc.replace("\\", "\\\\"))
    if doc_args:
        doc.append("")
        doc.append("    Args:")
        argwrap = textwrap.TextWrapper(width=88, initial_indent="        ", subsequent_indent="            ",
                                       break_on_hyphens=False, break_long_words=False)
        for pn, d in doc_args:
            doc.extend(argwrap.wrap(f"{pn}: {d}"))
    doc.append("")
    doc.append("    Returns:")
    doc.append("        The tool's JSON body. Raises FerroError on failure.")
    doc.append('    """')
    lines.extend(doc)

    if opt_items:
        lines.append("    args: Dict[str, Any] = {" + ", ".join(req_items) + "}")
        for k, pn in opt_items:
            lines.append(f"    if {pn} is not None:")
            lines.append(f"        args[{json.dumps(k)}] = {pn}")
        lines.append(f"    return _call({json.dumps(name)}, args)")
    else:
        lines.append(f"    return _call({json.dumps(name)}, {{" + ", ".join(req_items) + "})")
    return "\n".join(lines)


def generate(tools):
    names = [t["name"] for t in tools]
    if len(set(names)) != len(names):
        raise SystemExit("duplicate tool names in tools.json")
    out = [HEADER]
    for t in tools:
        out.append("\n\n" + gen_function(t) + "\n")
    out.append("\n\n#: Every tool name, in tools.json order.\n")
    out.append("TOOL_NAMES = (\n" + "".join(f"    {json.dumps(n)},\n" for n in names) + ")\n")
    return "".join(out)


def refresh():
    r = subprocess.run(["cargo", "run", "-q", "-p", "ferro-mcp", "--", "--tools-json"],
                       cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        raise SystemExit("cargo run -p ferro-mcp -- --tools-json failed")
    json.loads(r.stdout)  # validate before overwriting
    with open(SNAPSHOT, "w", encoding="utf-8", newline="\n") as f:
        f.write(r.stdout)


def main(argv):
    if "--refresh" in argv:
        refresh()
    with open(SNAPSHOT, encoding="utf-8") as f:
        tools = json.load(f)["tools"]
    text = generate(tools)
    if "--check" in argv:
        try:
            with open(OUTPUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print("python/ferro/_tools.py is out of date: run python3 scripts/gen_python.py")
            return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)} ({len(tools)} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
